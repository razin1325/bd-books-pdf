export async function searchBooks(query: string): Promise<Book[]> {
  if (!query || query.trim() === '') return [];
  const q = query.toLowerCase().trim();
  
  if (supabase) {
    const { data, error } = await supabase
      .from('books')
      .select('*')
      .or(`title.ilike.%${q}%,subject.ilike.%${q}%,class_name.ilike.%${q}%,description.ilike.%${q}%`)
      .eq('is_published', true);
    if (!error && data && data.length > 0) return data as Book[];
  }

  return MOCK_BOOKS.filter(b => {
    return (
      b.is_published &&
      (b.title.toLowerCase().includes(q) ||
        b.subject.toLowerCase().includes(q) ||
        b.class_name.toLowerCase().includes(q) ||
        b.description.toLowerCase().includes(q))
    );
  });
}

export async function getRelatedBooks(currentBook: Book, limit = 6): Promise<Book[]> {
  const sameClassBooks = await getBooksByClass(currentBook.class_slug);
  let related = sameClassBooks.filter(b => b.id !== currentBook.id && b.slug !== currentBook.slug);

  if (related.length < limit) {
    const allBooks = await getBooks();
    const additional = allBooks.filter(
      b => b.id !== currentBook.id && b.slug !== currentBook.slug && !related.some(r => r.id === b.id)
    );
    related = [...related, ...additional];
  }

  return related.slice(0, limit);
}

// Helper functions for Admin insertion, updating, and deletion
export async function createBook(bookData: Omit<Book, 'id' | 'created_at' | 'updated_at'>): Promise<Book> {
  const newBook: Book = {
    ...bookData,
    id: 'b-' + Date.now(),
    created_at: new Date().toISOString(),
    updated_at: new Date().toISOString(),
  };

  if (supabase) {
    const { data, error } = await supabase
      .from('books')
      .insert([bookData])
      .select()
      .single();
    if (!error && data) return data as Book;
  }

  MOCK_BOOKS.unshift(newBook);
  return newBook;
}

export async function updateBook(originalSlug: string, bookData: Partial<Book>): Promise<Book | null> {
  const updatedData = {
    ...bookData,
    updated_at: new Date().toISOString(),
  };

  if (supabase) {
    const { data, error } = await supabase
      .from('books')
      .update(updatedData)
      .eq('slug', originalSlug)
      .select()
      .single();
    if (!error && data) return data as Book;
  }

  const index = MOCK_BOOKS.findIndex(b => b.slug === originalSlug);
  if (index !== -1) {
    MOCK_BOOKS[index] = {
      ...MOCK_BOOKS[index],
      ...updatedData,
    };
    return MOCK_BOOKS[index];
  }
  return null;
}

export async function deleteBook(slug: string): Promise<boolean> {
  if (supabase) {
    const { error } = await supabase
      .from('books')
      .delete()
      .eq('slug', slug);
    if (!error) return true;
  }

  MOCK_BOOKS = MOCK_BOOKS.filter(b => b.slug !== slug);
  return true;
}
